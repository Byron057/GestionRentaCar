    private void aplicarPlaceholder(javax.swing.JTextField campo, String textoGuia) {
        // Configuración inicial del campo
        campo.setText(textoGuia);
        campo.setForeground(new java.awt.Color(153, 153, 153)); // Color gris para la guía

        // Añadimos el escuchador de foco
        campo.addFocusListener(new java.awt.event.FocusAdapter() {
            @Override
            public void focusGained(java.awt.event.FocusEvent evt) {
                // Si el texto actual es igual a la guía, lo borramos al entrar
                if (campo.getText().equals(textoGuia)) {
                    campo.setText("");
                    campo.setForeground(new java.awt.Color(60, 60, 60)); // Color oscuro al escribir
                }
            }

            @Override
            public void focusLost(java.awt.event.FocusEvent evt) {
                // Si el usuario sale del campo y lo dejó vacío, restauramos la guía
                if (campo.getText().trim().isEmpty()) {
                    campo.setText(textoGuia);
                    campo.setForeground(new java.awt.Color(153, 153, 153)); // Restaura el color gris
                }
            }
        });
    }
    private void aplicarPlaceholderComboBox(assets.ComboBoxRound combo) {
        // 1. Configuración inicial
        if (combo.getSelectedIndex() == -1) {
            combo.setForeground(new java.awt.Color(153, 153, 153)); // Gris
        } else {
            combo.setForeground(new java.awt.Color(60, 60, 60)); // Oscuro
        }

        // 2. Evento para cambiar el color al seleccionar
        combo.addItemListener(new java.awt.event.ItemListener() {
            @Override
            public void itemStateChanged(java.awt.event.ItemEvent evt) {
                if (evt.getStateChange() == java.awt.event.ItemEvent.SELECTED) {
                    combo.setForeground(new java.awt.Color(60, 60, 60)); 
                } 
                else if (combo.getSelectedIndex() == -1) {
                    combo.setForeground(new java.awt.Color(153, 153, 153)); 
                }
            }
        });
    }
