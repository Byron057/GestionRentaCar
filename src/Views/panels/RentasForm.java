    private void seleccionarItemComboBox(assets.ComboBoxRound combo,String textoBuscar){
        if(textoBuscar == null || textoBuscar.trim().isEmpty()) return;
        
        String textoLimpio = textoBuscar.trim().toLowerCase();

        for(int i = 0; i < combo.getItemCount(); i++){
            Object item = combo.getItemAt(i);
            if(item != null){
                String textoItem = item.toString().trim().toLowerCase();
                
                // Comparamos si el texto coincide (sea el nombre completo o contenga la cadena)
                if(textoItem.equals(textoLimpio) || textoItem.contains(textoLimpio)){
                    combo.setSelectedIndex(i);
                    combo.setForeground(new Color(60, 60, 60));
                    return;
                }
            }
        }
    }
